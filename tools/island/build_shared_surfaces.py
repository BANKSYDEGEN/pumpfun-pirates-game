#!/usr/bin/env python3
"""Reuse the plaza/hill compressed 12-layer atlas; strip town trim duplicates.
Reproducible offline build: python3 tools/island/build_shared_surfaces.py
Requires Pillow. Never touches foliage, water, signs, pirates or casino felt.
"""
from pathlib import Path
from PIL import Image
import io, json, struct, shutil
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'assets/island'

def read_glb(path):
    b = path.read_bytes(); n = struct.unpack_from('<I', b, 12)[0]
    return json.loads(b[20:20+n]), b[28+n:]

def texture_free(src, dst):
    d, blob = read_glb(src)
    image_views = {im['bufferView'] for im in d.get('images', [])}
    output = bytearray()
    def add(off, size):
        while len(output) % 4: output.append(0)
        start = len(output); output.extend(blob[off:off+size]); return start
    for i, view in enumerate(d['bufferViews']):
        if i in image_views:
            view.clear(); view.update(buffer=0, byteOffset=0, byteLength=0)
            continue
        if view['buffer'] == 0:
            view['byteOffset'] = add(view.get('byteOffset', 0), view['byteLength'])
        ext = view.get('extensions', {}).get('EXT_meshopt_compression')
        if ext and ext['buffer'] == 0:
            ext['byteOffset'] = add(ext.get('byteOffset', 0), ext['byteLength'])
    while len(output) % 4: output.append(0)
    d['buffers'][0]['byteLength'] = len(output)
    for name in ('images', 'textures', 'samplers'): d.pop(name, None)
    for m in d.get('materials', []):
        for key in list(m):
            if key.endswith('Texture'): del m[key]
        pbr = m.get('pbrMetallicRoughness', {})
        for key in list(pbr):
            if key.endswith('Texture'): del pbr[key]
    for name in ('extensionsUsed', 'extensionsRequired'):
        d[name] = [e for e in d.get(name, []) if e not in ('EXT_texture_webp', 'KHR_texture_basisu')]
    header = json.dumps(d, separators=(',', ':')).encode()
    header += b' ' * (-len(header) % 4)
    result = struct.pack('<III', 0x46546c67, 2, 28+len(header)+len(output)) + struct.pack('<II', len(header), 0x4e4f534a) + header + struct.pack('<II', len(output), 0x004e4942) + output
    dst.write_bytes(result)
    return len(result)

# Use the existing matching, mipmapped, GPU-compressed plaza/hill atlas, not a
# new uncompressed 2048 mosaic (which would cost more VRAM and bleed tile edges).
shutil.copyfile(OUT/'tex/lib_lo.ktx2', OUT/'tex/island_surfaces.ktx2')
d, blob = read_glb(OUT/'town_kit.webp.glb')
im = next(im for im in d['images'] if im['name'] == 'trim_albedo')
v = d['bufferViews'][im['bufferView']]
image = Image.open(io.BytesIO(blob[v.get('byteOffset',0):v.get('byteOffset',0)+v['byteLength']])).convert('RGBA')
fixtures = image.crop((0, 1760, 2048, 2048))
# Resize RGB independently: alpha encodes emission, not transparency.
r,g,b,a = fixtures.split()
fixtures = Image.merge('RGBA', (*Image.merge('RGB',(r,g,b)).resize((1024,144),Image.Resampling.LANCZOS).split(),a.resize((1024,144),Image.Resampling.NEAREST)))
fixtures.save(OUT/'tex/town_fixtures.webp', lossless=True, method=6)
regions=[]
for i in range(4): regions.append((f'plaster{i}',0,i*224,2048,i*224+220,4))
regions += [('timber',0,896,2048,958,6),('planks',0,960,2048,1150,7),('roof',0,1152,2048,1406,9),('stone',0,1408,2048,1630,1),('rubble',0,1632,2048,1758,5),('iron',1280,1760,1408,2046,10),('rope',1408,1760,1536,2046,11),('cloth',1664,1760,1792,2046,12)]
rules=[]
for name,x0,y0,x1,y1,layer in regions:
    # Preserve average painted tint / AO while replacing the pattern.
    pixels=image.crop((x0,y0,x1,y1)).convert('RGB').resize((1,1)).getpixel((0,0))
    def linear(c):
        c=c/255; return c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4
    rules.append(dict(name=name,rect=[x0/2048,y0/2048,x1/2048,y1/2048],layer=layer,tint=[round(linear(c),6) for c in pixels]))
(ROOT/'js/island/sharedSurfaceData.js').write_text('// Generated by tools/island/build_shared_surfaces.py; glTF UV coordinates.\nexport const TOWN_SURFACE_RULES = '+json.dumps(rules,separators=(',',':'))+';\n')
files={}
for low in (False,True):
    suffix='_low' if low else ''
    src=OUT/f'town_kit{suffix}.glb';dst=OUT/f'town_shared{suffix}.glb'
    files[dst.name]=dict(before=src.stat().st_size,after=texture_free(src,dst))
def mip_pixels(w,h):
    n=0
    while True:
        n+=w*h
        if w==h==1:return n
        w=max(1,w//2);h=max(1,h//2)
source_d, _ = read_glb(OUT/'town_kit.glb')
source_texture_bytes=sum(source_d['bufferViews'][i['bufferView']]['byteLength'] for i in source_d['images'])
report=dict(scope='Structural town trim + plaza/hill library; foliage/water/signs/NFTs/felt unchanged',
 structural_textures=dict(before=3,after=2),
 desktop_texture_download_bytes=dict(before=(OUT/'tex/lib.ktx2').stat().st_size+source_texture_bytes,after=(OUT/'tex/island_surfaces.ktx2').stat().st_size+(OUT/'tex/town_fixtures.webp').stat().st_size),
 desktop_gpu_bytes_estimate_BC7=dict(before=12*mip_pixels(1024,1024)+mip_pixels(2048,2048)+mip_pixels(1024,1024),after=12*mip_pixels(512,512)+4*mip_pixels(1024,144)),
 procedural_RG8_bytes=dict(before=13*2*mip_pixels(512,512),after=7*2*mip_pixels(512,512)),geometry_downloads=files)
(OUT/'tex/shared_surfaces_report.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))

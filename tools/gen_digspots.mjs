// [island-rework] generate the server's dig-spot lists from the shared registry js/island/digSpots.js.
//   node tools/gen_digspots.mjs          -> writes supabase/functions/pvp/digSpots.ts
//   node tools/gen_digspots.mjs --check  -> exits 1 if the file is stale (CI / tests/digspots.test.mjs)
// MAP_SPOTS = active + roll spots in registry order (the roll is p_spots[1 + roll % len]: append-only, never reorder).
// MAP_SPOTS_ALL = every active id (map_dig accepts these), cave last. Inactive (new, OFF) ids are listed in MAP_SPOTS_OFF for reference only.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const R = await import(new URL('../js/island/digSpots.js', import.meta.url));
const OUT = root + 'supabase/functions/pvp/digSpots.ts';
export function render() {
  const q = (a) => '[' + a.map(s => JSON.stringify(s)).join(', ') + ']';
  const off = R.DIG_SPOTS.filter(s => !s.active).map(s => s.id);
  return `// GENERATED by tools/gen_digspots.mjs from js/island/digSpots.js. DO NOT EDIT: change the registry and re-run the generator.
// Treasure-map dig spots (pvp_maps.spot). APPEND-ONLY: ids are never removed and MAP_SPOTS is never reordered (migration 026 rolls
// p_spots[1 + roll % len]; a map stores its spot id at drop time, so held maps stay valid whatever the island looks like).
export const MAP_SPOTS: string[] = ${q(R.rollIds())};
export const MAP_SPOTS_ALL: string[] = ${q(R.validIds())};
export const MAP_SPOTS_OFF: string[] = ${q(off)}; // registered for the island rework, switched OFF (not rolled, not diggable)
`; }
if (import.meta.url === `file://${process.argv[1]}`) {
  const want = render(); let have = ''; try { have = readFileSync(OUT, 'utf8'); } catch { }
  if (process.argv.includes('--check')) { if (have !== want) { console.error('digSpots.ts is stale: run node tools/gen_digspots.mjs'); process.exit(1); } console.log('digSpots.ts up to date'); }
  else { writeFileSync(OUT, want); console.log('wrote', OUT); }
}

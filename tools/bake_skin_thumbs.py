# [t2578u] Bake the ship-skin previews that phones show instead of live renders (js/skinPreview.js BAKED_ONLY).
# Uses the game's own renderPreview() on a desktop (fine pointer) page at HIGH quality, 1.5x DPR (540x300, base build),
# for every Battle Royale skin (pvp_<id>.webp) and every Waves skin (solo_<id>.webp), then rewrites manifest.js.
# Usage: serve the repo root (python3 -m http.server 8891 --bind 127.0.0.1) then: python3 tools/bake_skin_thumbs.py 8891
# Local only: every Supabase request is aborted (no prod reads or writes).
import asyncio, base64, json, os, sys
from playwright.async_api import async_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'ships', 'thumbs')
ARGS = ['--headless=new', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox', '--disable-dev-shm-usage']
JS = """async () => {
  const P = await import('/js/skinPreview.js'), S = await import('/js/pvpSkins.js'), C = await import('/js/shopCatalog.js'), K = await import('/js/skins.js'), W = await import('/js/shop.js');
  const pvp = [...new Set([...C.SKIN_ITEMS.map(i => i.id), ...S.TIERS.map(t => t.id), ...S.UNLOCKS.map(u => u.id)])].map(id => S.pvpSkin(id));
  const solo = [K.getSkin('classic'), ...W.wavesUnlocks().map(u => u.skin), ...K.SKINS];
  const out = { pvp: {}, solo: {} };
  for (const [set, list, extra] of [['pvp', pvp, { pvp: true }], ['solo', solo, null]]) for (const sk of list) {
    if (out[set][sk.id]) continue; const c = P.renderPreview(sk, {}, extra); if (!c) throw new Error('render failed ' + set + ' ' + sk.id);
    out[set][sk.id] = { w: c.width, h: c.height, url: c.toDataURL('image/webp', 0.92) };
    await new Promise(r => setTimeout(r, 0));
  }
  return out;
}"""
async def main():
    port = sys.argv[1] if len(sys.argv) > 1 else '8891'
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=ARGS)
        c = await b.new_context(service_workers='block', viewport={'width': 1280, 'height': 800}, device_scale_factor=1.5)
        await c.route('**/*supabase.co/**', lambda r: r.abort())
        await c.route('**/*.{mp3,ogg,wav,m4a}', lambda r: r.abort())
        pg = await c.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(f'http://127.0.0.1:{port}/index.html?quality=high', wait_until='domcontentloaded', timeout=180000)
        await pg.wait_for_function('window.PFP && PFP.renderer', timeout=180000)
        await pg.wait_for_timeout(3000)
        res = await pg.evaluate(JS)
        man = {'pvp': [], 'solo': []}
        for st, items in res.items():
            for sid, v in items.items():
                data = base64.b64decode(v['url'].split(',', 1)[1])
                with open(os.path.join(OUT, f'{st}_{sid}.webp'), 'wb') as f: f.write(data)
                man[st].append(sid); print(st, sid, v['w'], 'x', v['h'], len(data), 'bytes', flush=True)
        with open(os.path.join(OUT, 'manifest.js'), 'w') as f:
            f.write('// [t2578u] generated by tools/bake_skin_thumbs.py: skins with a pre-baked preview (phones show these, no 2nd WebGL context)\n')
            f.write('export const BAKED_SKINS = ' + json.dumps({k: sorted(v) for k, v in man.items()}) + ';\n')
        print('ERRORS', json.dumps(errs)); await b.close()
asyncio.run(main())

// [v330 perf] PUMPFUN PIRATES: regenerate the module preload lists from the real static import graph.
//   node tools/perf/gen_preload.mjs          -> rewrites js/preloadList.js + the BOOT <link rel="modulepreload"> block in index.html
//   node tools/perf/gen_preload.mjs --check  -> exit 1 when either is stale (tests/perfAndLoadV330.test.mjs runs this logic)
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export function importMap(root = ROOT) {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  return JSON.parse(html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports;
}
function resolve(im, from, spec) {
  if (spec.startsWith('.')) return path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  for (const k of Object.keys(im)) if (k.endsWith('/') ? spec.startsWith(k) : spec === k) return path.posix.normalize(im[k].replace(/^\.\//, '') + spec.slice(k.length));
  return null;
}
// static imports / re-exports only (dynamic import() is lazy on purpose); comments stripped first
export function staticGraph(entries, root = ROOT) {
  const im = importMap(root), seen = new Set(), q = [...entries];
  for (const e of entries) seen.add(e);
  while (q.length) { const f = q.shift(); if (/\.min\.js$/.test(f)) continue; let src; try { src = fs.readFileSync(path.join(root, f), 'utf8'); } catch { continue; }
    src = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
    const re = /(?:^|[;\n}])\s*(?:import|export)\s+(?:[\w*{}\s,$]+?\s+from\s+)?['"]([^'"]+)['"]/g; let m;
    while ((m = re.exec(src))) { const r = resolve(im, f, m[1]); if (!r || seen.has(r) || !fs.existsSync(path.join(root, r))) continue; seen.add(r); q.push(r); } }
  return [...seen];
}
export function lists(root = ROOT) {
  const boot = staticGraph(['js/main.js'], root);
  const bootSet = new Set(boot);
  // what SET SAIL / the harbor pulls in after the title: pvp.js, then the dock world (js/dock/index.js -> foot.js island)
  const harbor = staticGraph(['js/pvp.js', 'js/dock/index.js', 'js/island/foot.js'], root).filter(f => !bootSet.has(f));
  const order = (a) => [...a].sort((x, y) => (y.includes('three.module') - x.includes('three.module')) || x.localeCompare(y));
  return { boot: order(boot), harbor: order(harbor) };
}
const BEGIN = '<!-- [v330 perf] BOOT modulepreload (generated: node tools/perf/gen_preload.mjs) -->', END = '<!-- [v330 perf] /BOOT modulepreload -->';
export function renderHtmlBlock(boot) { return [BEGIN, ...boot.map(f => `<link rel="modulepreload" href="./${f}">`), END].join('\n'); }
export function renderListModule(harbor) {
  return `// [v330 perf] GENERATED by tools/perf/gen_preload.mjs from the static import graph: do not hand-edit (tests check it is fresh).\n` +
    `// HARBOR: modules SET SAIL / the harbor needs that the title screen has not loaded yet. js/main.js warms them with\n` +
    `// <link rel="modulepreload"> while the title sits idle (download + compile only, nothing runs), so entering the harbor skips the import waterfall.\n` +
    `export const HARBOR_MODULES = ${JSON.stringify(harbor, null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '",\n]')};\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { boot, harbor } = lists(); const check = process.argv.includes('--check');
  const htmlP = path.join(ROOT, 'index.html'), listP = path.join(ROOT, 'js/preloadList.js');
  let html = fs.readFileSync(htmlP, 'utf8'); const block = renderHtmlBlock(boot.filter(f => f !== 'js/main.js'));
  const has = html.includes(BEGIN), nextHtml = has ? html.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), block) : html;
  const nextList = renderListModule(harbor);
  if (check) { const ok = has && nextHtml === html && fs.existsSync(listP) && fs.readFileSync(listP, 'utf8') === nextList; console.log(ok ? 'preload lists fresh' : 'preload lists STALE: run node tools/perf/gen_preload.mjs'); process.exit(ok ? 0 : 1); }
  if (!has) { console.error('index.html is missing the BOOT modulepreload markers'); process.exit(1); }
  fs.writeFileSync(htmlP, nextHtml); fs.writeFileSync(listP, nextList);
  console.log('boot', boot.length, 'harbor', harbor.length);
}
